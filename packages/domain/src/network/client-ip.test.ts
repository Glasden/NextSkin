import { expect, test } from 'vitest'
import { resolveClientIp } from './client-ip.ts'

test.each([
  [null, '203.0.113.1', [], '203.0.113.1'],
  ['203.0.113.1', '127.0.0.1', ['127.0.0.0/8'], '203.0.113.1'],
  ['203.0.113.1, 10.0.0.2', '127.0.0.1', ['127.0.0.0/8', '10.0.0.0/8'], '203.0.113.1'],
  ['1.1.1.1', '203.0.113.1', ['127.0.0.0/8'], '203.0.113.1'],
  ['127.0.0.2, 127.0.0.3', '127.0.0.1', ['127.0.0.0/8'], '127.0.0.2'],
  ['1.1.1.1, bad, 10.0.0.2', '127.0.0.1', ['127.0.0.0/8', '10.0.0.0/8'], '10.0.0.2'],
  ['', '127.0.0.1', ['127.0.0.0/8'], '127.0.0.1'],
  ['203.0.113.1', '::ffff:127.0.0.1', ['127.0.0.0/8'], '203.0.113.1'],
  ['::ffff:192.0.2.1', '::1', ['::1'], '192.0.2.1'],
  ['::ffff:c000:201', '::1', ['::1'], '192.0.2.1'],
  ['2001:DB8:2::1', '2001:DB8:1::1', ['2001:db8:1::/48'], '2001:db8:2::1'],
  ['FE80::2%eth0', 'fe80::1%eth1', ['fe80::/10'], 'fe80::2'],
  ['203.0.113.1', null, ['127.0.0.0/8'], null],
  [null, 'invalid', [], null],
] as const)('XFF %s peer %s trusted %j → %s', (forwardedFor, peer, trustedProxies, result) => {
  expect(resolveClientIp({ forwardedFor, peer, trustedProxies })).toBe(result)
})
