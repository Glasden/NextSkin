import { tester } from '../rule-tester.ts'
import rule from './no-raw-color.ts'

tester.run('no-raw-color', rule, {
  valid: [
    'const token: string = "var(--color-accent)"',
    'const value = "#12345"',
    'const value = "#1234567"',
    'const value = "#ggg"',
    'const prose = "use #fff here"',
    'const value = "myrgb(1) recolor(2)"',
    'const style = { color: selectedColor }',
    { code: 'const view = <a href="#add" />', filename: 'x.tsx' },
    { code: 'const view = <a href={"#ADD"} />', filename: 'x.tsx' },
    { code: 'const view = <div style={{ display: "flex", opacity: 1 }} />', filename: 'x.tsx' },
    { code: 'const view = <div style={style} />', filename: 'x.tsx' },
    { code: 'const view = <div style={{ [property]: value }} />', filename: 'x.tsx' },
    { code: 'const view = <div data-style={{ color: value }} />', filename: 'x.tsx' },
  ],
  invalid: [
    ...['#abc', '#ABcD', '#123456', '#aAbBcCdD', ' #ABC \n'].map((value) => ({
      code: `const color = ${JSON.stringify(value)}`,
      errors: [{ messageId: 'raw' }],
    })),
    ...[
      'rgb',
      'rgba',
      'hsl',
      'hsla',
      'hwb',
      'lab',
      'lch',
      'oklab',
      'oklch',
      'color',
      'color-mix',
      'RGB',
      'OKLCH',
    ].flatMap((name) => [
      { code: `const color = "prefix ${name}(value)"`, errors: [{ messageId: 'raw' }] },
      { code: 'const color = `prefix ' + name + '(${value})`', errors: [{ messageId: 'raw' }] },
    ]),
    { code: 'const color = `${value}rgb(1 2 3)`', errors: [{ messageId: 'raw' }] },
    { code: 'const color = "\\u0072gb(1 2 3)"', errors: [{ messageId: 'raw' }] },
    { code: 'const view = <div title="#abc" />', filename: 'x.tsx', errors: [{ messageId: 'raw' }] },
    { code: 'const view = <a href="rgb(1 2 3)" />', filename: 'x.tsx', errors: [{ messageId: 'raw' }] },
    ...[
      'color',
      'background',
      'backgroundColor',
      'backgroundImage',
      'border',
      'borderColor',
      'borderTop',
      'borderTopColor',
      'borderRight',
      'borderRightColor',
      'borderBottom',
      'borderBottomColor',
      'borderLeft',
      'borderLeftColor',
      'outline',
      'outlineColor',
      'fill',
      'stroke',
      'boxShadow',
      'textShadow',
      'caretColor',
      'accentColor',
      'textDecorationColor',
      'columnRuleColor',
    ].flatMap((name) =>
      [name, JSON.stringify(name), `[${JSON.stringify(name)}]`].map((key) => ({
        code: `const view = <div style={{ ${key}: value }} />`,
        filename: 'x.tsx',
        errors: [{ messageId: 'style' }],
      })),
    ),
    {
      code: 'const view = <div style={{ color: "#fff" }} />',
      filename: 'x.tsx',
      errors: [{ messageId: 'style' }, { messageId: 'raw' }],
    },
  ],
})
